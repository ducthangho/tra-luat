"""Bundle tách mảnh: mỗi mảnh dưới ngưỡng WARN, nạp đúng mảnh được KHAI, kiểm cổng phát hiện mảnh lạc."""

import ast
import contextlib
import hashlib
import importlib
import io
import json
from pathlib import Path
import tempfile

TEST_ID = "wp433_bundled_tach_manh"

_TRAN = 0.7 * 280 * 1024   # 0,7·WARN của `_py_size_findings` = 200.704 B
# sha256 của `generate_bundled_module_bytes` trên base 0f9aa2a cho fixture `wp9001_a.py` (216 B); KHÔNG tính lại từ mã sau sửa.
_MOT_MANH_SHA256 = "73ad44659b63aea9b2f66fb1104c4c82deaa1ad1218e94adb80dcf38384441d7"
_KQ, _LY_DO = {}, {}   # V1–V32 của đặc tả §4, mỗi vế một khoá; khoá văng ⇒ False kèm lý do (vd nền từ chối symlink, V32)
_SRC, _SHA = "BUNDLED_FRAGMENT_SOURCES", "BUNDLED_FRAGMENT_SHARDS"
_M1 = "tl_test_fragments_bundled.py"
_M2, _M3, _M9, _M10 = (f"tl_test_fragments_bundled_{k}.py" for k in (2, 3, 9, 10))
_CONTRACT, _MISSING, _STALE = "BUNDLED_MODULE_CONTRACT", "BUNDLED_MODULE_MISSING", "GENERATED_BUNDLE_STALE"
_HAN = 100 * 1024
_DAU = '# -*- coding: utf-8 -*-\n"""Generated by tl_core.test_fragments; do not edit."""\n\n'


def _nguon(name, pad=""):
    return f'TEST_ID = "{name[:-3]}"\n_PAD = "{pad}"\n\n\ndef run(tl_module):\n    return True\n'


def _dong(name, pad=""):
    return f"    ({json.dumps(name)}, {json.dumps(_nguon(name, pad), ensure_ascii=False)}),\n"


def _van(muc, khai=None):
    """Render TAY một mảnh đúng định dạng sinh ra, ĐỘC LẬP generator: muc = [(tên, pad), …]; khai = tuple SHARDS hoặc None."""
    text = _DAU + f"{_SRC} = (\n" + "".join(_dong(n, pad) for n, pad in muc) + ")\n"
    if khai is not None:
        text += f"{_SHA} = (" + " ".join(f"{json.dumps(t)}," for t in khai) + ")\n"
    return text.encode("utf-8")


def _manh(path, names, khai=None, thua=b""):
    path.write_bytes(_van([(n, "") for n in names], khai) + thua)


def _nap(tf, scripts):
    try:
        return [c.test_id for c in tf.load_runtime_fragment_cases(scripts)], None, ""
    except Exception as exc:  # noqa: BLE001
        return None, getattr(exc, "code", type(exc).__name__), str(exc)


def _check(tl_module, root):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        try:
            rc = tl_module.main(["test-fragments-check", "--root", str(root), "--json"])
        except SystemExit as exc:
            rc = int(exc.code or 0)
    try:
        return rc, json.loads(out.getvalue())
    except ValueError:
        return rc, {}


def _gan(data):
    """Đọc ĐỘC LẬP (AST) một mảnh sinh ra: (hình dạng thân sau đúng MỘT docstring đầu, tên fragment, SHARDS hoặc None)."""
    body = ast.parse(data.decode("utf-8")).body
    if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0].value, "value", None), str):
        body = body[1:]
    ten = [n.targets[0].id if type(n) is ast.Assign and [type(t) for t in n.targets] == [ast.Name] else type(n).__name__ for n in body]
    gan = {}                                               # DỮ LIỆU: chỉ phép gán CHUẨN (Assign một đích Name), lần ĐẦU thắng;
    for n in body:                                         # HÌNH DẠNG (`ten`) mới theo luật loader (V3/V8)
        if type(n) is ast.Assign and [type(t) for t in n.targets] == [ast.Name] and n.targets[0].id in (_SRC, _SHA):
            gan.setdefault(n.targets[0].id, ast.literal_eval(n.value))
    return ten, [n for n, _ in gan.get(_SRC, ())], gan.get(_SHA)   # thiếu phép gán chuẩn ⇒ RỖNG, không văng (V3/V8 phán hình dạng)


def _bam(data):
    return hashlib.sha256(data).hexdigest()


def _do(base, tf, tl_module):
    """Trả 32 hàm đo theo thứ tự V1–V32; hàm nào văng thì khoá ấy False, các khoá khác vẫn được tính."""
    names = [f"wp9001_f{i}.py" for i in range(6)]
    ids = [n[:-3] for n in names]
    deu = ("deu", [(n, "x" * 40 * 1024) for n in names])  # 6 × 40 KiB, hạn 100 KiB ⇒ 2+2+2
    mot = ("mot", [("wp9001_a.py", "")])
    ba = [deu[1][:2], deu[1][2:4], deu[1][4:]]            # nhóm KỲ VỌNG của `deu`, khai tay cho cây cổng
    r3 = base / "r3" / "scripts"                          # mảnh viết tay, topology bundle (không có test_fragments/)

    def han(fn, limit=_HAN):
        old = tf._BUNDLED_SHARD_LIMIT
        tf._BUNDLED_SHARD_LIMIT = limit
        try:
            return fn()
        finally:
            tf._BUNDLED_SHARD_LIMIT = old

    def sinh(fixture, limit=_HAN):
        """Dựng thư mục fragment của fixture (một lần) rồi trả (thư mục, đầu ra generator)."""
        root = base / fixture[0] / "scripts" / "test_fragments"
        if not root.is_dir():
            root.mkdir(parents=True)
            for name, pad in fixture[1]:
                (root / name).write_bytes(_nguon(name, pad).encode("utf-8"))
        return root, han(lambda: tf.generate_bundled_modules(root), limit)

    def nhom(fixture, limit=_HAN):
        return [sorted(_gan(d)[1]) for _, d in sinh(fixture, limit)[1]]   # RANH mảnh; thứ tự trong mảnh là V4

    def ghi(ten, truoc=()):
        root, mods = sinh(deu)
        dest = base / ten
        dest.mkdir()
        for name in truoc:
            (dest / name).write_bytes(b"x = 0\n")
        han(lambda: tf.write_bundled_modules(root, dest))
        return mods, dest

    def loi(khai=(_M2, _M3), sua=None):
        """Dựng TAY ba mảnh hợp lệ trong r3, áp `sua`, trả (ids, mã lỗi, thông báo) của loader."""
        r3.mkdir(parents=True, exist_ok=True)
        for p in r3.iterdir():
            p.unlink()
        _manh(r3 / _M1, names[:2], khai)
        _manh(r3 / _M2, names[2:4])
        _manh(r3 / _M3, names[4:])
        if sua:
            sua()
        return _nap(tf, r3)

    def cong(nhom, sua=None):
        """Cây cổng dựng TAY: mảnh do `_van` render; vế KỲ VỌNG GHIM ở biên gọi generator (cùng bytes), nên đột biến định dạng
        generator không lan sang khoá cổng. `sua(scripts)` làm hỏng. Trả (vế kỳ vọng, {tên: bytes tệp thường}, rc, json)."""
        scripts, ten = base / f"cong{len(nhom)}" / "scripts", [_M1, _M2, _M3][:len(nhom)]
        mods = tuple((ten[k], _van(g, tuple(ten[1:]) if k == 0 and len(nhom) > 1 else None)) for k, g in enumerate(nhom))
        (scripts / "test_fragments").mkdir(parents=True, exist_ok=True)
        for p in scripts.glob("tl_test_fragments_bundled*.py"):
            p.unlink()
        for n, d in mods:
            (scripts / n).write_bytes(d)
        if sua:
            sua(scripts)
        goc, tf.generate_bundled_modules = tf.generate_bundled_modules, lambda *a, **k: mods
        try:
            rc, j = _check(tl_module, scripts.parent)
        finally:
            tf.generate_bundled_modules = goc
        dia = {p.name: p.read_bytes() for p in scripts.glob("tl_test_fragments_bundled*.py") if not p.is_symlink()}
        return mods, dia, rc, j

    def truong(j):
        return [j.get(k) for k in ("expected_sha256", "actual_sha256", "expected_bytes", "actual_bytes")]

    d5 = "đ" * 100                                         # 2 byte UTF-8 mỗi ký tự: đếm KÝ TỰ thay vì BYTE sẽ lệch ranh
    lech = ("lech", [(f"wp9001_x{i}.py", d5 + "x" * (i == 3)) for i in range(4)])
    s5 = len(_dong("wp9001_x0.py", d5).encode("utf-8"))   # x0–x2 cỡ s5; x3 = s5 + 1; hạn = 2·s5
    g6 = ["wp9001_g0.py", "wp9001_g1.py", "wp9001_g2.py"]
    lon = ("lon", [(g6[0], ""), (g6[1], "x" * 150 * 1024), (g6[2], "")])

    def v5():
        x = [n for n, _ in lech[1]]
        return len(_dong(x[3], d5 + "x").encode("utf-8")) == s5 + 1 and nhom(lech, 2 * s5) == [x[:2], x[2:3], x[3:]]

    def v6():
        return nhom(lon) == [g6[:1], g6[1:2], g6[2:]]

    def v8():                                              # hình dạng MỌI gói nhiều mảnh fragment sinh ra (deu, lech, lon)
        hinh = [[_gan(d)[0] for _, d in sinh(fx, *han_fx)[1]] for fx, *han_fx in ((deu,), (lech, 2 * s5), (lon,))]
        return hinh[0] == [[_SRC, _SHA], [_SRC], [_SRC]] and all(
            len(h) > 1 and h == [[_SRC, _SHA]] + [[_SRC]] * (len(h) - 1) for h in hinh)

    def v10():
        root, mods = sinh(deu)
        return len(mods) > 1 and han(lambda: tf.generate_bundled_module_bytes(root)) == mods[0][1]

    def v11():
        mods, dest = ghi("w11")
        return (len(mods) == 3 and sorted(p.name for p in dest.iterdir()) == sorted(n for n, _ in mods)
                and all((dest / n).read_bytes() == d for n, d in mods))

    def v13():
        truoc = loi()
        sau = loi(sua=lambda: _manh(r3 / _M9, ["wp9001_f6.py"]))
        return truoc[:2] == (ids, None) and sau[:2] == (ids, None)

    def v16():
        def doi():
            _manh(r3 / _M2, names[4:])
            _manh(r3 / _M3, names[2:4])
        return loi(sua=doi)[1] == _CONTRACT

    def quyet(rc, j):                                      # quyết định CLI đủ bốn trường
        return rc, j.get("ok"), j.get("status"), j.get("error")

    def hong(t, nhom=ba):                                  # MỖI nhiễu loạn một fixture riêng trên mảnh `t` ⇒ stale đủ quyết định
        def lat(k):                                        # và đủ bốn trường băm/độ dài, tính ĐỘC LẬP từ vế kỳ vọng + bytes đĩa
            return lambda d: d[:k(len(d))] + bytes([d[k(len(d))] ^ 1]) + d[k(len(d)) + 1:]
        bien = (lat(lambda n: 0), lat(lambda n: n // 2), lat(lambda n: n - 1),     # giữ độ dài: đầu | giữa | cuối
                lambda d: d + b"#", lambda d: d[:-1],                              # đổi độ dài: nối | cắt
                lambda d: d + b"# sua\n",                                         # nhiễu loạn của BASE (nối dòng trọn) — giữ nguyên
                lambda d: d.replace(b"\n", b"\r\n", 1))                          # kết thúc dòng: LF -> CRLF

        def mot(f):
            mods, dia, rc, j = cong(nhom, lambda s: (s / t).write_bytes(f((s / t).read_bytes())))
            ghep = (lambda m: m[_M1]) if len(mods) == 1 else (
                lambda m: b"".join(n.encode("utf-8") + b"\0" + m[n] for n, _ in mods))
            e, a = ghep(dict(mods)), ghep(dia)
            return quyet(rc, j) == (2, False, "stale", _STALE) and truong(j) == [_bam(e), _bam(a), len(e), len(a)]
        return all([mot(f) for f in bien])

    def v23():
        def mot_lac(ten):                                  # MỖI mảnh lạc một fixture riêng: MỘT chữ số và HAI chữ số
            mods, dia, rc, j = cong(ba, lambda s: (s / ten).write_bytes(b"x = 0\n"))
            lac = sorted(set(dia) - {n for n, _ in mods})  # tệp đánh số trên đĩa mà generator KHÔNG trả tên
            return quyet(rc, j) == (2, False, "stale", _STALE) and lac == [ten] and j.get("extra_shards") == lac
        return all([mot_lac(ten) for ten in (_M9, _M10)])

    def v25():
        _, _, rc, j = cong(ba, lambda s: (s / _M2).unlink())
        return quyet(rc, j) == (2, False, "stale", _STALE) and j["shards"][1]["actual_bytes"] is None

    def v27():
        mods, dia, rc, j = cong([mot[1]])                  # một mảnh: current ⇒ ok (rc 0) VÀ stale ⇒ GENERATED_BUNDLE_STALE
        g, d = mods[0][1], dia[_M1]
        return (len(mods) == 1 and truong(j) == [_bam(g), _bam(d), len(g), len(d)]
                and quyet(rc, j) == (0, True, "current", None) and hong(_M1, [mot[1]]))

    def v28():                                             # băm VÀ độ dài đều của chính chuỗi tên + NUL + bytes
        mods, dia, rc, j = cong(ba)                         # nhiều mảnh: current ⇒ ok (rc 0)
        e = b"".join(n.encode("utf-8") + b"\0" + d for n, d in mods)
        a = b"".join(n.encode("utf-8") + b"\0" + dia.get(n, b"") for n, _ in mods)
        return (len(mods) > 1 and truong(j) == [_bam(e), _bam(a), len(e), len(a)]
                and (rc, j.get("ok"), j.get("status")) == (0, True, "current"))

    def v29():
        mods, dia, _, j = cong(ba)
        return len(mods) > 1 and j.get("shards") == [
            {"name": n, "expected_bytes": len(d), "actual_bytes": len(dia[n]) if n in dia else None} for n, d in mods]

    def v31():
        scripts = Path(tf.__file__).resolve().parent.parent
        repo = scripts / "test_fragments"
        if repo.is_dir():                                  # cây dev: đo CẢ đầu ra generator LẪN tệp trên đĩa
            real = tf.generate_bundled_modules(repo)
            sizes = [len(d) for _, d in real] + [len((scripts / n).read_bytes()) for n, _ in real]
        else:                                              # gói phát hành: đo mảnh 1 và mọi mảnh nó KHAI; thiếu ⇒ văng ⇒ False
            khai = _gan((scripts / _M1).read_bytes())[2] or ()
            sizes = [len((scripts / n).read_bytes()) for n in (_M1, *khai)]
        return bool(sizes) and all(size <= _TRAN for size in sizes)

    def v32():
        ngoai, dut = base / "ngoai.py", base / "dut.py"    # đích symlink NGOÀI thư mục mảnh; `dut` không tồn tại (symlink ĐỨT)

        def lien(path, data):                              # data None ⇒ symlink đứt; nền không tạo được symlink ⇒ văng ⇒ False + lý do
            if data is not None:
                ngoai.write_bytes(data)
            path.unlink(missing_ok=True)
            path.symlink_to(ngoai if data is not None else dut)
        hai = [(t, x) for t in (_M1, _M2) for x in (1, None)]   # mảnh 1 / mảnh phụ × symlink trỏ đúng / symlink đứt
        nap = [loi(sua=lambda: lien(r3 / t, x and (r3 / t).read_bytes()))[1] for t, x in hai]
        ok = [cong(ba, lambda s: lien(s / t, x and (s / t).read_bytes()))[3].get("ok") for t, x in hai]
        giu = []
        for t, x in hai:
            dest = base / f"w32{t}{x}"
            dest.mkdir()
            lien(dest / t, x and b"giu nguyen\n")
            with contextlib.suppress(Exception):
                han(lambda: tf.write_bundled_modules(sinh(deu)[0], dest))
            giu.append(ngoai.read_bytes() if x else dut.exists())
        return nap == [_CONTRACT] * 4 and ok == [False] * 4 and giu == [b"giu nguyen\n", False] * 2

    return (
        lambda: [_bam(d) for _, d in sinh(mot)[1]] == [_MOT_MANH_SHA256],                                  # V1
        lambda: _bam(tf.generate_bundled_module_bytes(sinh(mot)[0])) == _MOT_MANH_SHA256,                  # V2
        lambda: [_gan(d)[0] for _, d in sinh(("hai", [("wp9001_a.py", ""), ("wp9001_b.py", "")]))[1]] == [[_SRC]],  # V3
        lambda: [_gan(d)[1] for _, d in sinh(deu)[1]] == [names[:2], names[2:4], names[4:]],               # V4
        v5, v6,
        lambda: [n for n, _ in sinh(deu)[1]] == [_M1, _M2, _M3],                                           # V7
        v8,                                                                                                # V8 (+ mảnh phụ, mọi gói nhiều mảnh)
        lambda: _gan(sinh(deu)[1][0][1])[2] == (_M2, _M3),                                                 # V9
        v10, v11,
        lambda: not (ghi("w12", truoc=(_M9,))[1] / _M9).exists(),                                          # V12
        v13,
        lambda: loi(sua=lambda: (r3 / _M2).unlink())[1] == _MISSING,                                       # V14
        lambda: f"scripts/{_M2}" in loi(sua=lambda: (r3 / _M2).unlink())[2],                               # V15
        v16,
        lambda: loi(sua=lambda: _manh(r3 / _M3, names[3:]))[1] == _CONTRACT,       # V17: f3 cuối mảnh 2 VÀ đầu mảnh 3
        lambda: loi(sua=lambda: _manh(r3 / _M3, names[4:], (_M2,)))[1] == _CONTRACT,                       # V18
        lambda: loi(khai=())[1] == _CONTRACT,                                                              # V19
        lambda: loi(khai=(_M3,))[1] == _CONTRACT,                                                          # V20
        lambda: loi(sua=lambda: _manh(r3 / _M1, names[:2], (_M2, _M3), thua=b"0\n"))[1] == _CONTRACT,      # V21
        lambda: loi(sua=lambda: _manh(r3 / _M3, names[4:], thua=b"0\n"))[1] == _CONTRACT,                  # V22
        v23,
        lambda: [hong(_M1), hong(_M2)] == [True, True],                        # V24: mảnh CHÍNH và mảnh phụ
        v25,
        lambda: quyet(*cong([mot[1]], lambda s: (s / _M1).unlink())[2:]) == (2, False, "missing", _MISSING),  # V26
        v27, v28, v29,
        lambda: tf._BUNDLED_SHARD_LIMIT == 196608,                                                         # V30
        v31, v32,
    )


def run(tl_module):
    tf = importlib.import_module("tl_core.test_fragments")
    _KQ.clear(), _LY_DO.clear()
    with tempfile.TemporaryDirectory(prefix="wp433_bt_") as tmp:
        for so, fn in enumerate(_do(Path(tmp), tf, tl_module), start=1):
            try:
                _KQ[f"V{so}"] = fn() is True
            except Exception as exc:  # noqa: BLE001 — văng ⇒ khoá False, không bỏ dở các khoá sau
                _KQ[f"V{so}"], _LY_DO[f"V{so}"] = False, f"{type(exc).__name__}: {exc}"
    return len(_KQ) == 32 and all(value is True for value in _KQ.values())
