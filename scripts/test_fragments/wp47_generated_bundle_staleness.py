# -*- coding: utf-8 -*-
"""Exercise the opt-in land gate through the public CLI."""

import contextlib
import io
import json
from pathlib import Path
import tempfile


TEST_ID = "wp47_generated_bundle_staleness"


_FRAGMENT_SOURCE = (
    b'TEST_ID = "wp47_fixture"\n\n\n'
    b'def run(tl_module):\n'
    b'    return True\n'
)
_BUNDLED_SOURCE = (
    b'# -*- coding: utf-8 -*-\n'
    b'"""Generated by tl_core.test_fragments; do not edit."""\n\n'
    b'BUNDLED_FRAGMENT_SOURCES = (\n'
    b'    ("wp47_fixture.py", "TEST_ID = \\"wp47_fixture\\"\\n\\n\\ndef run(tl_module):\\n    return True\\n"),\n'
    b')\n'
)


def _invoke(tl_module, root):
    stdout = io.StringIO()
    with contextlib.redirect_stdout(stdout):
        try:
            rc = tl_module.main([
                "test-fragments-check", "--root", str(root), "--json"])
        except SystemExit as exc:
            rc = int(exc.code or 0)
    try:
        payload = json.loads(stdout.getvalue())
    except (TypeError, ValueError):
        payload = {}
    return rc, payload


def run(tl_module):
    with tempfile.TemporaryDirectory(prefix="wp47_bundle_check_") as temp:
        root = Path(temp)
        scripts = root / "scripts"
        fragments = scripts / "test_fragments"
        fragments.mkdir(parents=True)
        (fragments / "wp47_fixture.py").write_bytes(_FRAGMENT_SOURCE)
        bundled = scripts / "tl_test_fragments_bundled.py"
        bundled.write_bytes(_BUNDLED_SOURCE)

        current_rc, current = _invoke(tl_module, root)
        bundled.write_bytes(b"stale\n")
        stale_rc, stale = _invoke(tl_module, root)
        bundled.unlink()
        missing_rc, missing = _invoke(tl_module, root)

    return (
        current_rc == 0
        and current.get("ok") is True
        and current.get("status") == "current"
        and stale_rc != 0
        and stale.get("error") == "GENERATED_BUNDLE_STALE"
        and missing_rc != 0
        and missing.get("error") == "BUNDLED_MODULE_MISSING"
    )
